"""
Grounded Gemini / Vertex AI Operational Explanation Service
============================================================

Provides server-side operational explanations for inventory alerts and transfer
recommendations based strictly on facts pre-computed by backend business rules.

Security & Integrity Guarantees:
1. Data Minimization: Sends minimal operational supply chain fields only.
   Rejects and forbids patient identifiable information (PHI) or secret values.
2. Strict Schema Validation & Length Caps: Output is bounded and schema-validated.
3. Resilient Deterministic Fallback: When Vertex AI / Gemini is unconfigured,
   offline, rate-limited, or times out, seamlessly returns a deterministic
   rule-based explanation.
4. Honest Provenance: Never fakes a response. The source field is set to
   'gemini-1.5-flash' only when real AI execution succeeds, and
   'deterministic-rule-engine' (with is_fallback=True) otherwise.
"""

from __future__ import annotations

import json
import logging
from typing import Any, Optional
import httpx
from pydantic import BaseModel, Field, ValidationError

from app.core.config import settings

logger = logging.getLogger(__name__)


# ── Strict Schemas ────────────────────────────────────────────────────────────

class OperationalFacts(BaseModel):
    """Sanitized operational facts object calculated by backend rules.
    Contains NO patient-identifiable data or secrets.
    """
    alert_id: Optional[str] = None
    facility_name: str = Field(..., max_length=150)
    district: str = Field(..., max_length=100)
    item_name: str = Field(..., max_length=150)
    current_usable_stock: int = Field(..., ge=0)
    safety_reserve: int = Field(..., ge=0)
    projected_deficit: int = Field(..., ge=0)
    days_until_stockout: Optional[int] = Field(default=None, ge=0)
    recommended_action: str = Field(..., max_length=200)
    donor_facility_name: Optional[str] = Field(default=None, max_length=150)
    transfer_quantity: Optional[int] = Field(default=None, ge=0)
    urgency_reason: Optional[str] = Field(default=None, max_length=250)
    is_simulated: bool = Field(default=True)


class GroundedExplanation(BaseModel):
    """Schema-validated explanation for clinical/operations staff."""
    summary: str = Field(..., max_length=300, description="Brief 1-2 sentence overview")
    operational_rationale: str = Field(..., max_length=600, description="Supply chain rationale")
    recommended_action: str = Field(..., max_length=300, description="Concrete next operational step")
    confidence_note: str = Field(..., max_length=200, description="Deterministic invariant or model confidence")
    source: str = Field(..., description="'gemini-1.5-flash' or 'deterministic-rule-engine'")
    is_fallback: bool = Field(..., description="True if generated by deterministic template fallback")
    provenance: str = Field(default="Simulated data")


# ── Deterministic Fallback Generator ──────────────────────────────────────────

def generate_deterministic_fallback(facts: OperationalFacts) -> GroundedExplanation:
    """Generate a 100% deterministic, grounded explanation directly from rule facts.
    Guaranteed to execute with zero external network or model dependencies.
    """
    days_text = f"in {facts.days_until_stockout} days" if facts.days_until_stockout is not None else "imminently"
    donor_text = facts.donor_facility_name or "District Central Medical Depot"
    qty_text = str(facts.transfer_quantity or facts.projected_deficit)

    summary = (
        f"Critical stock breach projected {days_text} for {facts.item_name} "
        f"at {facts.facility_name} ({facts.district})."
    )

    rationale = (
        f"Usable stock ({facts.current_usable_stock} units) will breach the protected "
        f"safety reserve threshold ({facts.safety_reserve} units) by {facts.projected_deficit} units. "
        f"Safe candidate facility '{donor_text}' holds surplus capacity without compromising its own reserve."
    )

    action = (
        f"Approve inter-facility replenishment transfer of {qty_text} units "
        f"from {donor_text} to {facts.facility_name}."
    )

    confidence = "Evaluated deterministically via safe-donor rules and consumption invariants."

    return GroundedExplanation(
        summary=summary[:300],
        operational_rationale=rationale[:600],
        recommended_action=action[:300],
        confidence_note=confidence[:200],
        source="deterministic-rule-engine",
        is_fallback=True,
        provenance="Simulated data" if facts.is_simulated else "Operational data",
    )


# ── Server-Side Explanation Service ───────────────────────────────────────────

async def generate_operational_explanation(facts: OperationalFacts) -> GroundedExplanation:
    """
    Generates a grounded explanation for the provided operational facts.
    Uses Gemini if GEMINI_API_KEY is configured and available; otherwise
    seamlessly falls back to deterministic template generation.
    """
    api_key = settings.gemini_api_key
    if not api_key:
        logger.debug("GEMINI_API_KEY not configured; using deterministic rule-based explanation")
        return generate_deterministic_fallback(facts)

    endpoint = (
        f"https://generativelanguage.googleapis.com/v1beta/models/"
        f"{settings.gemini_model}:generateContent?key={api_key}"
    )

    system_instruction = (
        "You are an operational logistics assistant for a healthcare supply chain sentinel. "
        "Explain the inventory shortage and recommended transfer strictly using the provided "
        "operational facts. Do not invent any numbers, facilities, or medical conditions. "
        "Return valid JSON only matching the schema: summary, operational_rationale, recommended_action, confidence_note."
    )

    prompt_content = {
        "contents": [
            {
                "parts": [
                    {
                        "text": (
                            f"{system_instruction}\n\n"
                            f"Operational Facts:\n{facts.model_dump_json(indent=2)}\n\n"
                            "Respond with raw JSON only (no markdown, no code blocks):"
                        )
                    }
                ]
            }
        ],
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": 400,
            "responseMimeType": "application/json",
        },
    }

    try:
        async with httpx.AsyncClient(timeout=settings.gemini_timeout_seconds) as client:
            resp = await client.post(endpoint, json=prompt_content)

        if resp.status_code != 200:
            logger.warning(
                "Gemini API returned non-200 status code: %s (falling back to deterministic rules)",
                resp.status_code,
            )
            return generate_deterministic_fallback(facts)

        data = resp.json()
        candidates = data.get("candidates", [])
        if not candidates:
            logger.warning("Gemini response contained no candidates; using fallback")
            return generate_deterministic_fallback(facts)

        raw_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
        parsed = json.loads(raw_text)

        explanation = GroundedExplanation(
            summary=str(parsed.get("summary", ""))[:300],
            operational_rationale=str(parsed.get("operational_rationale", ""))[:600],
            recommended_action=str(parsed.get("recommended_action", ""))[:300],
            confidence_note=str(parsed.get("confidence_note", "Generated via Google Gemini grounded on operational facts."))[:200],
            source=settings.gemini_model,
            is_fallback=False,
            provenance="Simulated data" if facts.is_simulated else "Operational data",
        )
        return explanation

    except (httpx.TimeoutException, httpx.RequestError) as net_err:
        logger.info("Gemini request network timeout/error (%s); falling back cleanly", type(net_err).__name__)
        return generate_deterministic_fallback(facts)
    except (json.JSONDecodeError, ValidationError, Exception) as err:
        logger.warning("Gemini output parsing/validation failed (%s); using deterministic fallback", type(err).__name__)
        return generate_deterministic_fallback(facts)
